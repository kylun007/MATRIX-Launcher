const progress = (label: string, b: number, t: number) => { if (Date.now() - last > 10000) { console.log(`${label}: ${(b/1e6).toFixed(1)} / ${(t/1e6).toFixed(1)} MB`); last = Date.now(); } };
const resource = join(root, 'minecraft');
instance.versionId = await installLoader(instance, resource, undefined, data.settings, signal, progress);
await installLoaderLibraries(await Version.parse(resource, instance.versionId), resource, undefined, data.settings, signal, progress);
