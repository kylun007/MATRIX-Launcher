setNetworkTransport(nativeHttpsFetch);
const root = resolve('.smoke/live-game'); const data = defaults(root);
const instance = { id: '92668173-955b-4d5b-98ce-c1cdc0dd005a', name: 'Fabric live smoke', minecraft: '1.20.1', loader: 'fabric' as const, loaderVersion: '0.16.14', installed: true, versionId: '' };
