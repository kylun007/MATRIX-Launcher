import { createPrivateKey, createPublicKey, sign, verify } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { basename } from 'node:path';
import { parseUpdateInfo } from 'electron-updater/out/providers/Provider.js';

const manifestPath = process.argv[2];
if (!manifestPath) throw new Error('Uso: node scripts/sign-update-manifest.mjs <release/latest.yml|release/beta.yml>');
const config = JSON.parse(await readFile('config/distribution.json', 'utf8'));
const appPackage = JSON.parse(await readFile('package.json', 'utf8'));
const privatePem = process.env.MATRIX_UPDATE_SIGNING_KEY;
if (!privatePem || !config.updateManifestPublicKey) throw new Error('Configure MATRIX_UPDATE_SIGNING_KEY e updateManifestPublicKey antes de assinar.');
const channel = process.env.MATRIX_UPDATE_CHANNEL ?? 'stable';
if (!['stable', 'beta'].includes(channel) || basename(manifestPath) !== (channel === 'stable' ? 'latest.yml' : 'beta.yml')) throw new Error('O manifesto não corresponde ao canal selecionado.');
const tag = process.env.GITHUB_REF_NAME ?? `v${appPackage.version}`;
if (tag !== `v${appPackage.version}`) throw new Error('Tag de release não corresponde à versão do package.json.');
const privateKey = createPrivateKey(privatePem);
const publicKey = createPublicKey(config.updateManifestPublicKey);
const manifest = await readFile(manifestPath);
const update = parseUpdateInfo(manifest.toString('utf8'), basename(manifestPath), new URL(`https://github.com/${config.githubOwner}/${config.githubRepo}/releases/download/${tag}/${basename(manifestPath)}`));
if (update.version !== appPackage.version || !Array.isArray(update.files) || update.files.length === 0 || update.files.some(file => !file.url.toLowerCase().endsWith('.exe') || !/^[A-Za-z0-9+/]{86}==$/.test(file.sha512 ?? '') || !Number.isSafeInteger(file.size) || file.size <= 0)) throw new Error('Manifesto de atualização inválido, incompleto ou divergente da versão do app.');
const signature = sign(null, manifest, privateKey);
if (!verify(null, manifest, publicKey, signature)) throw new Error('A chave privada não corresponde à chave pública configurada.');
await writeFile(`${manifestPath}.sig`, `${signature.toString('base64')}\n`, { flag: 'wx' });
console.log(`Manifesto assinado e verificado: ${manifestPath}.sig`);
